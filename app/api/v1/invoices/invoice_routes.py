@invoice_bp.route("/projects/<project_id>/invoices", methods=["GET"])
@openapi_doc(
    summary="List invoices for a project, optionally filtered by ?type=/?tag_id=/?service_month=/?worker_id=",
    query=ListInvoicesFilterQuery,
    tags=["invoices"],
)
@jwt_required()
@require_permission("project:read")
@require_project_access(write=False)
def list_invoices(project_id: str):
    """List invoices for a project, optionally filtered by ?type=/?tag_id=/?service_month=/?worker_id=."""
    invoice_type_param = normalize_invoice_type_value(request.args.get("type"))
    tag_id_param = request.args.get("tag_id")
    try:
        parsed_type = InvoiceType(invoice_type_param) if invoice_type_param else None
    except ValueError:
        valid = ", ".join(t.value for t in InvoiceType)
        return _error_response(
            "ValidationError",
            f"Invalid type '{invoice_type_param}'. Must be one of: {valid}",
            400,
        )

    # service_month/worker_id are the labor-payments drill-down filters — validated
    # via Pydantic so malformed input returns 422 (mirrors ExportLaborQuery).
    try:
        filters = ListInvoicesFilterQuery(
            service_month=request.args.get("service_month"),
            worker_id=request.args.get("worker_id"),
        )
    except ValidationError as e:
        return format_validation_error(e)

    service_month_date = (
        datetime.strptime(filters.service_month, "%Y-%m").date().replace(day=1) if filters.service_month else None
    )

    container = get_container()
    try:
        results = container.list_invoices_usecase.execute(
            ListInvoicesRequest(
                project_id=UUID(project_id),
                invoice_type=parsed_type,
                tag_id=UUID(tag_id_param) if tag_id_param else None,
                service_month=service_month_date,
                worker_id=filters.worker_id,
            )
        )
    except ValueError as e:
        return _error_response("ValidationError", str(e), 400)

    project_uuid = UUID(project_id)

    # One scan for the released-funds split, one scan for the spent split — down from
    # four whole-table aggregations (sum_funds_released + sum_funds_released_split +
    # sum_company_spent + sum_personal_spent) to two. funds_released_total is derived
    # from the RAW (pre-quantization) split components so it exactly reconciles with
    # their sum, per the port's documented invariant.
    funds_released_company_raw, funds_released_personal_raw = container.invoice_repository.sum_funds_released_split(
        project_uuid
    )
    funds_released_total = money(funds_released_company_raw + funds_released_personal_raw)
    funds_released_company_total = money(funds_released_company_raw)
    funds_released_personal_total = money(funds_released_personal_raw)

    company_spent_raw, personal_spent_raw = container.invoice_repository.sum_spent_split(project_uuid)
    company_spent_total = money(company_spent_raw)
    personal_spent_total = money(personal_spent_raw)

    # Resolve company once; reuse for company_name, paid_by_company/paid_by_personal
    # enrichment, and the payment-method-id lookups below (was resolved 3x before).
    from app import db
    from app.infrastructure.database.models.company import CompanyModel

    _company_id = _get_project_company_id(project_uuid)
    if _company_id is not None:
        _company_row = db.session.get(CompanyModel, _company_id)
        company_name = _company_row.legal_name if _company_row is not None else None
    else:
        company_name = None

    # Single query over both flag columns (was two separate queries); membership-test
    # per invoice row. IDs come back as UUIDs from the DB; compare as strings to
    # match InvoiceResponse.payment_method_id.
    _company_pm_ids, _personal_pm_ids = _load_company_and_personal_payment_method_ids(_company_id)
    company_pm_id_strs: set[str] = {str(uid) for uid in _company_pm_ids}
    personal_pm_id_strs: set[str] = {str(uid) for uid in _personal_pm_ids}

    invoice_dicts = []
    for r in results:
        d = dataclasses.asdict(r)
        # r.payment_method_id is a str (InvoiceResponse serialises it that way)
        _enrich_invoice_with_company_payment(d, r.payment_method_id, company_pm_id_strs)
        _enrich_invoice_with_personal_payment(d, r.payment_method_id, personal_pm_id_strs)
        invoice_dicts.append(d)

    # Batch-enrich refunds_invoice_number in one query (no N+1) so the list/mobile
    # views can render "Refund of <number>" for linked refund invoices.
    link_id_strs = {r.refunds_invoice_id for r in results if r.refunds_invoice_id}
    number_by_id: dict[str, str] = {}
    if link_id_strs:
        rows = (
            db.session.query(InvoiceModel.id, InvoiceModel.invoice_number)
            .filter(InvoiceModel.id.in_([UUID(x) for x in link_id_strs]))
            .all()
        )
        number_by_id = {str(_id): _num for _id, _num in rows}
    for d, r in zip(invoice_dicts, results):
        d["refunds_invoice_number"] = number_by_id.get(r.refunds_invoice_id) if r.refunds_invoice_id else None

    # Batch-enrich has_bank_refund (one query) for the materials_services rows so the
    # list/mobile views can show the company-vs-bank refund-source indicator.
    ms_ids = [UUID(r.id) for r in results if r.type == InvoiceType.MATERIALS_SERVICES.value]
    bank_refunded = container.invoice_repository.refund_source_ids(ms_ids) if ms_ids else set()
    for d, r in zip(invoice_dicts, results):
        d["has_bank_refund"] = r.type == InvoiceType.MATERIALS_SERVICES.value and UUID(r.id) in bank_refunded

    # Batch-enrich applied_to_invoice_number (mirrors refunds_invoice_number above) so
    # the list/mobile views can render "Applied to <number>" for avoir-linked returns.
    applied_link_id_strs = {r.applied_to_invoice_id for r in results if r.applied_to_invoice_id}
    applied_number_by_id: dict[str, str] = {}
    if applied_link_id_strs:
        rows = (
            db.session.query(InvoiceModel.id, InvoiceModel.invoice_number)
            .filter(InvoiceModel.id.in_([UUID(x) for x in applied_link_id_strs]))
            .all()
        )
        applied_number_by_id = {str(_id): _num for _id, _num in rows}
    for d, r in zip(invoice_dicts, results):
        d["applied_to_invoice_number"] = (
            applied_number_by_id.get(r.applied_to_invoice_id) if r.applied_to_invoice_id else None
        )

    # Reverse enrichment: paid_with_returns — for each row, the avoir returns applied to
    # it. One batch query over the whole page's ids (no N+1).
    page_ids = [UUID(r.id) for r in results]
    applied_summaries = container.invoice_repository.applied_return_summaries(page_ids) if page_ids else {}
    for d, r in zip(invoice_dicts, results):
        d["paid_with_returns"] = applied_summaries.get(UUID(r.id), [])

    return jsonify(
        {
            "invoices": invoice_dicts,
            "total": len(invoice_dicts),
            "funds_released_total": funds_released_total,
            "company_spent_total": company_spent_total,
            "funds_released_company_total": funds_released_company_total,
            "funds_released_personal_total": funds_released_personal_total,
            "personal_spent_total": personal_spent_total,
            "company_name": company_name,
        }
    )


