def _load_company_and_personal_payment_method_ids(company_id: "UUID | None") -> "tuple[set[UUID], set[UUID]]":
    """Return (company_payment_ids, personal_payment_ids) for a company in one query.

    Single query over both flag columns, replacing the two separate queries
    _get_company_payment_method_ids / _get_personal_payment_method_ids would
    otherwise issue. Takes an already-resolved company_id so callers that need
    it for other purposes (e.g. company_name) don't re-resolve it. Returns two
    empty sets when company_id is None.
    """
    if company_id is None:
        return set(), set()
    from app import db
    from app.infrastructure.database.models.payment_method import PaymentMethodModel

    rows = (
        db.session.query(
            PaymentMethodModel.id,
            PaymentMethodModel.is_company_payment,
            PaymentMethodModel.is_personal_payment,
        )
        .filter(PaymentMethodModel.company_id == company_id)
        .all()
    )
    company_ids = {r[0] for r in rows if r[1]}
    personal_ids = {r[0] for r in rows if r[2]}
    return company_ids, personal_ids


def _enrich_refunds_invoice_number(invoice_dict: dict, refunds_invoice_id_str: "str | None") -> None:
    """Inject refunds_invoice_number into an invoice dict in-place.

    When refunds_invoice_id is present, fetches the linked invoice's number in one
    db.session.get call so the FE can display "Refund of INV-2026-0001" without
    a separate round-trip.  Sets None when the link is absent or target not found.
    """
    if not refunds_invoice_id_str:
        invoice_dict["refunds_invoice_number"] = None
        return
    from app import db
    from uuid import UUID as _UUID

    linked = db.session.get(InvoiceModel, _UUID(refunds_invoice_id_str))
    invoice_dict["refunds_invoice_number"] = linked.invoice_number if linked is not None else None


def _enrich_applied_to_invoice_number(invoice_dict: dict, applied_to_invoice_id_str: "str | None") -> None:
    """Inject applied_to_invoice_number into an invoice dict in-place.

    Mirrors _enrich_refunds_invoice_number: single db.session.get lookup so the FE can
    display "Applied to INV-2026-0001" for avoir-settled returns without a second
    round-trip. Sets None when the link is absent or the target is not found.
    """
    if not applied_to_invoice_id_str:
        invoice_dict["applied_to_invoice_number"] = None
        return
    from app import db
    from uuid import UUID as _UUID

    linked = db.session.get(InvoiceModel, _UUID(applied_to_invoice_id_str))
    invoice_dict["applied_to_invoice_number"] = linked.invoice_number if linked is not None else None


def _enrich_paid_with_returns(invoice_dict: dict, invoice_id_str: str) -> None:
    """Inject paid_with_returns into an invoice dict in-place.

    Lists the avoir return invoices whose applied_to_invoice_id points at this
    invoice, as [{"invoice_number": ..., "total_amount": ...}, ...]. Empty list when
    no returns are applied to it.
    """
    from uuid import UUID as _UUID

    invoice_uuid = _UUID(invoice_id_str)
    summaries = get_container().invoice_repository.applied_return_summaries([invoice_uuid])
    invoice_dict["paid_with_returns"] = summaries.get(invoice_uuid, [])


def _enrich_has_bank_refund(invoice_dict: dict, invoice_id_str: str, invoice_type: str) -> None:
    """Inject has_bank_refund into an invoice dict in-place.

    True only when this materials_services expense has ≥1 linked refund invoice
    (i.e. a supplier/vendor sent money back — "refunded by bank"). The company
    signal rides on refundable_status == 'refunded'. False for all other types.
    """
    if invoice_type != InvoiceType.MATERIALS_SERVICES.value:
        invoice_dict["has_bank_refund"] = False
        return
    from uuid import UUID as _UUID

    sources = get_container().invoice_repository.refund_source_ids([_UUID(invoice_id_str)])
    invoice_dict["has_bank_refund"] = _UUID(invoice_id_str) in sources


def _enrich_invoice_with_company_payment(
    invoice_dict: dict,
    payment_method_id_str: "str | None",
    company_pm_id_strs: "set[str]",
) -> dict:
    """Inject paid_by_company into an invoice dict in-place and return it.

    paid_by_company is True only when the invoice has a payment_method_id that
    belongs to the project's company and is flagged is_company_payment.
    False when payment_method_id is null or the project has no company.
    """
    invoice_dict["paid_by_company"] = payment_method_id_str is not None and payment_method_id_str in company_pm_id_strs
    return invoice_dict


def _enrich_invoice_with_personal_payment(
    invoice_dict: dict,
    payment_method_id_str: "str | None",
    personal_pm_id_strs: "set[str]",
) -> dict:
    """Inject paid_by_personal into an invoice dict in-place and return it.

    paid_by_personal is True only when the invoice has a payment_method_id that
    belongs to the project's company and is flagged is_personal_payment.
    False when payment_method_id is null or the project has no company.
    """
    invoice_dict["paid_by_personal"] = (
        payment_method_id_str is not None and payment_method_id_str in personal_pm_id_strs
    )
    return invoice_dict


